import assert from 'node:assert/strict';
import fs from 'node:fs';
import {filterEvents,eventHours} from '../../vienna-events/filters.mjs';
import {validateCatalog} from './catalog-validation.mjs';

const catalog=JSON.parse(fs.readFileSync(new URL('../../vienna-events/events.json',import.meta.url),'utf8'));
validateCatalog(catalog,'2026-10-31');
const state={period:'custom',from:'2026-11-01',to:'2026-11-01',types:['museum'],saved:[],area:'all'};
const results=(changes={},day='2026-10-31',time='00:00')=>filterEvents(catalog.events,{...state,...changes},day,time);
const ids=entries=>entries.map(e=>e.id);
const museums=catalog.events.filter(e=>e.type==='museum');
assert.equal(museums.length,24);
assert.equal(results().length,8);
for(const id of ['wien-museum-free-sunday','roemermuseum-free-sunday','uhrenmuseum-free-sunday','beethoven-museum-free-sunday','beethoven-pasqualati-free-sunday'])assert.ok(ids(results()).includes(id));
assert.ok(!ids(results()).includes('hgm-free-sunday'),'HGM must not appear on its 1 November closure');
assert.ok(!museums.some(e=>/Pratermuseum|Hermesvilla|Virgilkapelle|Haydnhaus|Neidhart/.test(e.title)),'Closed branches must not get visit dates');
assert.ok(ids(results({from:'2026-12-06',to:'2026-12-06'})).includes('hgm-free-sunday'));
assert.ok(!ids(results({from:'2026-11-02',to:'2026-11-02'})).includes('wien-museum-permanent'),'No Wien Museum visit on Monday');
assert.ok(!ids(results({from:'2026-12-25',to:'2026-12-25'})).includes('wien-museum-permanent'));
assert.ok(ids(results({from:'2026-11-04',to:'2026-11-04'})).includes('secession-free-wednesday'));
assert.ok(ids(results({from:'2026-11-05',to:'2026-11-05'})).includes('leopold-porr-night'));
assert.ok(ids(results({from:'2026-11-29',to:'2026-11-29'})).includes('kunsthalle-mq-free-sunday'));
const combined=results({types:['museum','music']});
assert.deepEqual(new Set(ids(combined)),new Set([...ids(results()),...ids(results({types:['music']}))]));
assert.equal(results({outdoor:true}).length,0);
assert.deepEqual(ids(results({savedOnly:true,saved:['roemermuseum-free-sunday']})),['roemermuseum-free-sunday']);
assert.deepEqual(ids(results({query:'Hoher Markt'})),['roemermuseum-free-sunday']);
const main=museums.find(e=>e.id==='wien-museum-permanent');
assert.equal(eventHours(main,'2026-11-01').time,'10:00');
assert.equal(eventHours(main,'2026-11-05').timeEnd,'21:00');
assert.ok(ids(results({period:'today'},'2026-11-05','20:00')).includes(main.id),'Thursday evening stays available');
assert.ok(!ids(results({period:'today'},'2026-11-05','21:00')).includes(main.id));
assert.equal(eventHours(museums.find(e=>e.id==='doew-free-exhibition'),'2026-11-05').timeEnd,'19:00');
assert.equal(eventHours(museums.find(e=>e.id==='fire-brigade-museum-free'),'2026-11-03').time,'14:00');
assert.ok(!museums.find(e=>e.id==='fire-brigade-museum-free').dates.includes('2026-12-08'));
assert.equal(museums.find(e=>e.id==='fire-brigade-museum-dec8').time,'09:00');
assert.equal(museums.find(e=>e.id==='judenplatz-happy-friday').timeEnd,'14:00');
assert.match(museums.find(e=>e.id==='beethoven-museum-free-sunday').timeLabel,/13:00 \/ 14:00/);
assert.match(museums.find(e=>e.id==='horten-free-thursday-20261210').availability,/sold out/);
assert.equal(museums.find(e=>e.id==='horten-free-thursday-20261210').dates.length,1);
assert.match(museums.find(e=>e.id==='belvedere-free-friday-20261120').availability,/13 November/);
assert.ok(catalog.museumGuide.otherFree.length>=18);
const bad=structuredClone(catalog);bad.events.find(e=>e.id===main.id).hoursByWeekday['4'].timeEnd='08:00';
assert.throws(()=>validateCatalog(bad,'2026-10-31'));
console.log('Museum checks passed: dated admission, holiday/seasonal closures, varying hours, lunch breaks, reservations, combined filters, search and saved events.');
